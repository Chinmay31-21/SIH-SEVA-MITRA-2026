create policy "Anyone can read market sources" on public.market_sources
  for select using (true);
create policy "Anyone can read market prices" on public.market_prices
  for select using (true);
create policy "Anyone can read active listings" on public.produce_listings
  for select using (status = 'active');
create policy "Anyone can read storage facilities" on public.storage_facilities
  for select using (true);

create policy "Farmers manage their profile" on public.farmer_profiles
  for all using (auth.uid() = id) with check (auth.uid() = id);
create policy "Farmers manage their listings" on public.produce_listings
  for all using (auth.uid() = farmer_id) with check (auth.uid() = farmer_id);
create policy "Farmers see their orders" on public.produce_orders
  for select using (auth.uid() = buyer_id or auth.uid() = seller_id);
create policy "Farmers create orders" on public.produce_orders
  for insert with check (auth.uid() = buyer_id);
create policy "Farmers manage their bookings" on public.storage_bookings
  for all using (auth.uid() = farmer_id) with check (auth.uid() = farmer_id);
create policy "Farmers read their sensor data" on public.sensor_readings
  for select using (auth.uid() = farmer_id);
