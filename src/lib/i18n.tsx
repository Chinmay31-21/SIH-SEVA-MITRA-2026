interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  languageCode: string;
  t: (text: string, fallback?: string) => string;
  languages: typeof languages;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window !== "undefined") {
      const stored = localStorage.getItem(LANGUAGE_LOCAL_STORAGE_KEY) as Language | null;
      if (stored && languages.includes(stored)) {
        return stored;
      }
    }
    return "English";
  });

  const languageCode = useMemo(() => LANGUAGE_CODES[language] ?? "en", [language]);

  const setLanguage = (newLang: Language) => {
    setLanguageState(newLang);
    if (typeof window !== "undefined") {
      localStorage.setItem(LANGUAGE_LOCAL_STORAGE_KEY, newLang);
      window.dispatchEvent(new CustomEvent("krishi_language_changed", { detail: newLang }));

      // Synchronize with Google Translate cookie if present
      const code = LANGUAGE_CODES[newLang] || "en";
      const domain = window.location.hostname;
      document.cookie = `googtrans=/en/${code}; path=/;`;
      if (domain !== "localhost") {
        document.cookie = `googtrans=/en/${code}; domain=${domain}; path=/;`;
      }

      // Trigger change on Google Translate combo if loaded
      const combo = document.querySelector<HTMLSelectElement>(".goog-te-combo");
      if (combo && combo.value !== code) {
        combo.value = code;
        combo.dispatchEvent(new Event("change"));
      }
    }
  };

  useEffect(() => {
    const handleStorage = (e: StorageEvent) => {
      if (e.key === LANGUAGE_LOCAL_STORAGE_KEY && e.newValue) {
        if (languages.includes(e.newValue as Language)) {
          setLanguageState(e.newValue as Language);
        }
      }
    };
    window.addEventListener("storage", handleStorage);
    return () => window.removeEventListener("storage", handleStorage);
  }, []);

  const t = (text: string, fallback?: string): string => {
    if (!text) return text;
    if (language === "English") return fallback ?? text;

    // Direct lookup in translations dictionary
    const item = translations[text.trim()];
    if (item && item[language]) {
      return item[language]!;
    }

    // Try case-insensitive lookup
    const lower = text.trim().toLowerCase();
    for (const [key, value] of Object.entries(translations)) {
      if (key.toLowerCase() === lower && value[language]) {
        return value[language]!;
      }
    }

    return fallback ?? text;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        languageCode,
        t,
        languages,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    // Provide a graceful fallback if used outside Provider
    return {
      language: "English" as Language,
      setLanguage: () => {},
      languageCode: "en",
      t: (text: string, fallback?: string) => fallback ?? text,
      languages,
    };
  }
  return context;
}

export function useTranslation() {
  return useLanguage();
}

export function T({ children, fallback }: { children: string; fallback?: string }) {
  const { t } = useLanguage();
  return <>{t(children, fallback)}</>;
}
